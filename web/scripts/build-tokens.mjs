// Writes src/theme/tokens.css from src/theme/palette.json, the validated palette, so a colour on the
// site can only be one the validator passed. Light is the paper; dark is the blackboard, taken when
// the reader asks for it or the system prefers it. Print always takes the paper.
//
// Slot one is the answer (what the model wrote), slot two the reward (what training paid), slot
// three the held-out checks (what was confirmed); slots four to eight are the methods in fixed order
// (base, SFT, DPO, GRPO, SFT then GRPO). The floor is the control gray with a hatch.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const web = join(dirname(fileURLToPath(import.meta.url)), "..");
const palette = JSON.parse(readFileSync(join(web, "src", "theme", "palette.json"), "utf8"));

const ROLES = ["answer", "reward", "checks", "m0", "m1", "m2", "m3", "m4"];

export function tokenLines(mode) {
  const p = palette[mode];
  if (!p) throw new Error(`palette.json has no ${mode} block`);
  if (p.categorical.length !== 8) throw new Error(`the ${mode} categorical palette needs eight slots`);
  return [
    `--gh-surface: ${p.surface};`,
    `--gh-raised: ${p.raised};`,
    `--gh-hairline: ${p.hairline};`,
    `--gh-margin: ${p.margin};`,
    `--gh-ink: ${p.ink};`,
    `--gh-ink2: ${p.ink2};`,
    `--gh-control: ${p.control};`,
    ...p.categorical.map((c, i) => `--gh-cat-${i + 1}: ${c};`),
    ...ROLES.map((role, i) => `--gh-${role}: ${p.categorical[i]};`),
    ...p.sequential.map((c, i) => `--gh-seq-${i + 1}: ${c};`),
    ...p.diverging.map((c, i) => `--gh-div-${i + 1}: ${c};`),
    ...Object.entries(p.status).map(([name, c]) => `--gh-${name}: ${c};`),
    `color-scheme: ${mode};`,
  ];
}

function block(selector, mode, indent = "  ", important = false) {
  const body = tokenLines(mode)
    .map((line) => `${indent}  ${important ? line.replace(/;$/, " !important;") : line}`)
    .join("\n");
  return `${indent}${selector} {\n${body}\n${indent}}`;
}

const css = [
  "/* Generated by scripts/build-tokens.mjs from src/theme/palette.json. Do not edit by hand. */",
  block(":root", "light", ""),
  "",
  "@media (prefers-color-scheme: dark) {",
  block(':root:not([data-theme="light"])', "dark"),
  "}",
  "",
  block(':root[data-theme="dark"]', "dark", ""),
  "",
  "@media print {",
  block(":root", "light", "  ", true),
  "}",
  "",
].join("\n");

mkdirSync(join(web, "src", "theme"), { recursive: true });
writeFileSync(join(web, "src", "theme", "tokens.css"), css);
console.log("tokens: src/theme/tokens.css written from src/theme/palette.json (light and dark)");
